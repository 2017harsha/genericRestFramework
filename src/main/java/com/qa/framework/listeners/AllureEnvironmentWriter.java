package com.qa.framework.listeners;

import com.qa.framework.config.ConfigKeys;
import com.qa.framework.config.ConfigManager;

import java.io.IOException;
import java.io.OutputStream;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.Properties;
import java.util.concurrent.atomic.AtomicBoolean;

/** Writes {@code environment.properties} into allure-results (shown on the Allure overview page). */
public final class AllureEnvironmentWriter {

    private static final AtomicBoolean WRITTEN = new AtomicBoolean(false);

    private AllureEnvironmentWriter() {
    }

    public static void writeOnce() {
        if (!WRITTEN.compareAndSet(false, true)) {
            return;
        }
        ConfigManager cfg = ConfigManager.get();
        Properties props = new Properties();
        props.setProperty("Environment", cfg.environment().id().toUpperCase());
        props.setProperty("Base URL", cfg.raw(ConfigKeys.BASE_URL).orElse("-"));
        props.setProperty("Auth type", cfg.raw(ConfigKeys.AUTH_TYPE).orElse("none"));
        props.setProperty("Java", System.getProperty("java.version"));
        props.setProperty("OS", System.getProperty("os.name"));
        String build = System.getenv("BUILD_URL");
        if (build != null) {
            props.setProperty("Jenkins build", build);
        }

        Path dir = Paths.get(System.getProperty("allure.results.directory", "target/allure-results"));
        try {
            Files.createDirectories(dir);
            try (OutputStream out = Files.newOutputStream(dir.resolve("environment.properties"))) {
                props.store(out, "Generated by api-test-framework");
            }
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
